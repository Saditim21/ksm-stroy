// Writes src/data/mnogofamilna/snapshot.js (`npm run mn-snapshot`):
// Многофамилна's apartments as of SNAPSHOT_DATE, the rows the availability
// store's built-in path makes from src/constants/mnogofamilnaFallbackData.js,
// as a compact module that decodes them once at import (spec §5.1). The
// Многофамилна pages prerender their numbers from it. Run it again whenever
// the built-in data changes. src/data/mnogofamilna/snapshot.test.js holds the
// module to the store's own rows, and to its size.
//
// The module stores each block a column at a time, which gzip packs tighter
// than a row at a time, since a floor's values recur on the next floor. A text
// column joins its values with „|“. A listed column (type, exposure, status)
// holds one base-36 digit a row, its value's index in the column's list.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import { getMnogoAFallbackData, getMnogoBFallbackData } from '../../src/constants/mnogofamilnaFallbackData.js'
import { normalizeStatus } from '../../src/utils/propertyStatus.js'

const OUT = fileURLToPath(new URL('../../src/data/mnogofamilna/snapshot.js', import.meta.url))

// The date the built-in data is as of (spec §2). src/config/facts.test.js
// holds Home's MNOGO_DATED to the module's.
const SNAPSHOT_DATE = '01.12.2025'

// The store's rows for a block, restated from src/data/availability/store.js
// (its rowsOf), as that module does not load in plain Node: floor key 0, the
// garages that no page lists, is left out, and every status goes through
// normalizeStatus().
function rowsOf(floors) {
  return Object.entries(floors)
    .filter(([floor]) => Number(floor) !== 0)
    .flatMap(([floor, apartments]) => apartments.map((apartment) => ({
      unit: apartment.apartment ?? '',
      floor,
      type: apartment.вид ?? '',
      area: { built: apartment.built ?? '', ideal: apartment.ideal ?? '', total: apartment.total ?? '' },
      exposure: apartment.изложение ?? '',
      status: normalizeStatus(apartment.status),
      price: apartment.цена ?? '',
    })))
}

// The project's slots, as the store names them.
const BLOCKS = {
  'block-a': rowsOf(getMnogoAFallbackData()),
  'block-b': rowsOf(getMnogoBFallbackData()),
}

// Each column's value in a row, in the order the module stores them. The
// decoder below names the same columns.
const COLUMNS = {
  unit: (row) => row.unit,
  floor: (row) => row.floor,
  type: (row) => row.type,
  built: (row) => row.area.built,
  ideal: (row) => row.area.ideal,
  total: (row) => row.area.total,
  exposure: (row) => row.exposure,
  status: (row) => row.status,
  price: (row) => row.price,
}
const LISTED = ['type', 'exposure', 'status']

// Each listed column's values across both blocks, in the order they first
// appear. One base-36 digit indexes at most 36.
const LISTS = Object.fromEntries(LISTED.map((name) => {
  const list = [...new Set(Object.values(BLOCKS).flat().map(COLUMNS[name]))]
  if (list.length > 36) throw new Error(`The ${name} column has ${list.length} values; a digit indexes 36.`)
  return [name, list]
}))

// A block's columns. Every value must be text without the separator. A block
// without rows would decode as one empty row, so it is refused too. The bad
// value is found by its place: an `undefined` among them is bad as well, and
// find() would give it back as if none were.
function columnsOf(slot, rows) {
  if (rows.length === 0) throw new Error(`${slot} has no apartments.`)
  return Object.fromEntries(Object.entries(COLUMNS).map(([name, valueOf]) => {
    const values = rows.map(valueOf)
    const at = values.findIndex((value) => typeof value !== 'string' || value.includes('|'))
    if (at !== -1) throw new Error(`${slot}: the ${name} ${String(JSON.stringify(values[at]))} is not text, or holds the separator „|“.`)
    if (LISTED.includes(name)) return [name, values.map((value) => LISTS[name].indexOf(value).toString(36)).join('')]
    return [name, values.join('|')]
  }))
}

const literal = (value) => JSON.stringify(value)

const lists = Object.entries(LISTS).map(([name, list]) => `  ${name}: ${literal(list)},`)
const blocks = Object.entries(BLOCKS).map(([slot, rows]) => [
  `  ${literal(slot)}: {`,
  ...Object.entries(columnsOf(slot, rows)).map(([name, column]) => `    ${name}: ${literal(column)},`),
  '  },',
].join('\n'))

const source = `// GENERATED by scripts/mnogofamilna/build-snapshot.mjs (npm run mn-snapshot)
// from src/constants/mnogofamilnaFallbackData.js. Do not edit it by hand.
//
// Многофамилна's apartments as of MN_SNAPSHOT_DATE. MN_SNAPSHOT_DATA is the
// project's slice of useAvailability().data: the rows the store's built-in
// path gives (src/data/availability/store.js), floor 0 (the garages) left out
// and every status canonical, decoded here once at import.
//
// Each block is stored a column at a time, a row's values at the same place
// in every column. A text column joins its values with „|“. A listed column
// (type, exposure, status) holds one base-36 digit a row, its value's index
// in LISTS.

export const MN_SNAPSHOT_DATE = ${literal(SNAPSHOT_DATE)}

const LISTS = {
${lists.join('\n')}
}

const BLOCKS = {
${blocks.join('\n')}
}

const text = (column) => column.split('|')
const listed = (column, list) => Array.from(column, (digit) => list[parseInt(digit, 36)])

// A block's rows, in the shape of src/services/sheetsCore.js's apartment row.
function rows(block) {
  const floor = text(block.floor)
  const type = listed(block.type, LISTS.type)
  const built = text(block.built)
  const ideal = text(block.ideal)
  const total = text(block.total)
  const exposure = listed(block.exposure, LISTS.exposure)
  const status = listed(block.status, LISTS.status)
  const price = text(block.price)
  return text(block.unit).map((unit, i) => ({
    unit,
    floor: floor[i],
    type: type[i],
    area: { built: built[i], ideal: ideal[i], total: total[i] },
    exposure: exposure[i],
    status: status[i],
    price: price[i],
  }))
}

export const MN_SNAPSHOT_DATA = {
  'mnogofamilna-sgrada': Object.fromEntries(Object.entries(BLOCKS).map(([slot, block]) => [slot, rows(block)])),
}
`

writeFileSync(OUT, source)
const count = Object.values(BLOCKS).reduce((sum, rows) => sum + rows.length, 0)
console.log(`src/data/mnogofamilna/snapshot.js: ${count} apartments as of ${SNAPSHOT_DATE}, ${gzipSync(source).length} B gzip`)
