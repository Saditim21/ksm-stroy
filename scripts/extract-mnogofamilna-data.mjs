import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync('src/components/FourTowersFloorMap.jsx', 'utf8')
const marker = 'export const FLOOR_DATA = '
const start = src.indexOf(marker)
if (start === -1) throw new Error('FLOOR_DATA not found')
const objStart = src.indexOf('{', start)
let depth = 0, end = objStart
for (let i = objStart; i < src.length; i++) {
  if (src[i] === '{') depth++
  if (src[i] === '}') depth--
  if (depth === 0) { end = i; break }
}
const literal = src.slice(objStart, end + 1)
// planImage values reference imported image identifiers — stub them all with null
const idents = [...new Set([...literal.matchAll(/planImage:\s*([A-Za-z_$][\w$]*)/g)].map((m) => m[1]))]
const FLOOR_DATA = new Function(...idents, `return ${literal}`)(...idents.map(() => null))

const stripArea = (s) => (s ?? '').replace(/\s*м²\s*$/u, '').trim()
const toRow = (apt) => ({
  apartment: apt.имот ?? '',
  built: stripArea(apt.застроенаПлощ),
  ideal: '',
  вид: apt.вид ?? '',
  total: stripArea(apt.общаПлощ),
  изложение: apt.изложение ?? '',
  status: apt.статус ?? 'Свободен',
  цена: '',
})

const result = {}
for (const [blockKey, blockName] of [['A', 'A'], ['B', 'B']]) {
  const floors = FLOOR_DATA[blockKey] ?? {}
  const out = {}
  for (const floor of Object.keys(floors).map(Number).sort((a, b) => a - b)) {
    out[floor] = (floors[floor].apartments ?? []).map(toRow)
  }
  result[blockName] = out
}

// 1) Fallback module (same shape as googleSheets transformToApartmentData output)
const moduleSrc = `// GENERATED by scripts/extract-mnogofamilna-data.mjs — do not edit by hand.
// Fallback data for Многофамилна сграда, used when Google Sheets are unreachable.
const MNOGO_A = ${JSON.stringify(result.A, null, 2)}

const MNOGO_B = ${JSON.stringify(result.B, null, 2)}

export const getMnogoAFallbackData = () => MNOGO_A
export const getMnogoBFallbackData = () => MNOGO_B
`
writeFileSync('src/constants/mnogofamilnaFallbackData.js', moduleSrc)

// 2) Owner CSVs (UTF-8 BOM so Cyrillic imports cleanly into Google Sheets/Excel)
const HEADER = 'Етаж,Апартамент,Вид,Застроена,Идеални,Обща,Изложение,Статус'
const csvEscape = (v) => (/[",]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v)
for (const [blockName, file] of [['A', 'google-sheets-data/mnogofamilna-vhod-a.csv'], ['B', 'google-sheets-data/mnogofamilna-vhod-b.csv']]) {
  const lines = [HEADER]
  for (const [floor, rows] of Object.entries(result[blockName])) {
    for (const r of rows) {
      lines.push([floor, r.apartment, r.вид, r.built, r.ideal, r.total, r.изложение, r.status].map(csvEscape).join(','))
    }
  }
  writeFileSync(file, '\uFEFF' + lines.join('\n')) // BOM so Cyrillic opens correctly in Excel
  console.log(`${file}: ${lines.length - 1} rows`)
}
for (const b of ['A', 'B']) {
  const floors = Object.keys(result[b])
  const total = Object.values(result[b]).reduce((n, arr) => n + arr.length, 0)
  console.log(`Вход ${b}: floors [${floors.join(',')}], ${total} apartments`)
}
